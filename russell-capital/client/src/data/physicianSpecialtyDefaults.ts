/**
 * Convert a specialty profile to ClientFactFinderData-compatible format
 * for auto-filling calculators
 */
export function specialtyToFactFinderData(profile: PhysicianSpecialtyProfile) {
  return {
    clientName: `${profile.specialty} Physician`,
    age: profile.typicalAge,
    retirementAge: profile.retirementAge,
    annualIncome: profile.avgCompensation,
    filingStatus: profile.filingStatus,
    state: profile.typicalState,
    spouseAge: profile.typicalAge - 2,
    spouseIncome: profile.spouseIncome,
    dependents: profile.dependents,
    cashSavings: profile.cashSavings,
    taxableInvestments: profile.taxableInvestments,
    iraBalance: profile.iraBalance,
    rothBalance: profile.rothBalance,
    k401Balance: profile.k401Balance,
    homeValue: profile.homeValue,
    mortgageBalance: profile.mortgageBalance,
    totalMortgageInterest: Math.round(profile.mortgageBalance * 0.065),
    otherDebt: 0,
    monthlyExpenses: profile.monthlyExpenses,
    hasLTC: false,
    primarySchoolDebt: profile.medianStudentDebt,
    primarySchoolInterestRate: profile.avgStudentLoanRate,
    // Physician-specific
    medicalSpecialty: profile.specialty,
    trainingStage: "Attending",
    practiceType: profile.practiceType,
  };
}


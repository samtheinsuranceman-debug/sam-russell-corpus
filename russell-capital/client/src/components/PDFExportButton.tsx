import { Button } from "@/components/ui/button";
import { Download } from "lucide-react";
import { useState } from "react";

interface PDFExportButtonProps {
  title: string;
  inputs: Record<string, string | number>;
  results: Record<string, string | number>;
  projectionData?: Array<Record<string, number>>;
  irsCitations?: string[];
}

export default function PDFExportButton({
  title,
  inputs,
  results,
  irsCitations,
}: PDFExportButtonProps) {
  const [isLoading, setIsLoading] = useState(false);

  const handleExport = () => {
    setIsLoading(true);
    setTimeout(() => {
      window.print();
      setIsLoading(false);
    }, 300);
  };

  return (
    <>
      <Button
        variant="outline"
        onClick={handleExport}
        disabled={isLoading}
        className="flex items-center gap-2 border-slate-300 dark:border-slate-700 dark:bg-slate-800 dark:text-white"
      >
        <Download size={16} />
        Export PDF
      </Button>

      <div className="hidden print:block fixed inset-0 bg-white dark:bg-slate-800 text-slate-900 dark:text-white p-6 overflow-auto">
        <div className="max-w-4xl mx-auto">
          <header className="mb-6 border-b border-slate-200 dark:border-slate-700 pb-4">
            <h1 className="text-2xl font-bold text-slate-900 dark:text-white">
              Russell Capital Solutions
            </h1>
            <div className="h-1 w-16 bg-green-600 mt-2" />
            <h2 className="text-xl font-semibold mt-2">{title} Report</h2>
            <p className="text-sm text-slate-500 dark:text-slate-400">
              Generated on {new Date().toLocaleDateString()}
            </p>
          </header>

          <section className="mb-6">
            <h3 className="text-lg font-medium mb-2">Input Summary</h3>
            <table className="w-full border-collapse border border-slate-300 dark:border-slate-700">
              <tbody>
                {Object.entries(inputs).map(([key, value]) => (
                  <tr key={key} className="border-b dark:border-slate-700">
                    <td className="p-2 font-medium">{key}</td>
                    <td className="p-2">{value}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </section>

          <section className="mb-6">
            <h3 className="text-lg font-medium mb-2">Results</h3>
            <table className="w-full border-collapse border border-slate-300 dark:border-slate-700">
              <tbody>
                {Object.entries(results).map(([key, value]) => (
                  <tr key={key} className="border-b dark:border-slate-700">
                    <td className="p-2 font-medium">{key}</td>
                    <td className="p-2">{value}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </section>

          {irsCitations && irsCitations.length > 0 && (
            <section className="mb-6">
              <h3 className="text-lg font-medium mb-2">IRS Citations</h3>
              <ul className="list-disc pl-5 space-y-1">
                {irsCitations.map((citation, index) => (
                  <li key={index} className="text-sm">
                    {citation}
                  </li>
                ))}
              </ul>
            </section>
          )}

          <footer className="mt-8 text-center text-sm text-slate-500 dark:text-slate-400 border-t border-slate-200 dark:border-slate-700 pt-4">
            Generated by Russell Capital Solutions — Physician Financial Planning
          </footer>
        </div>
      </div>
    </>
  );
}
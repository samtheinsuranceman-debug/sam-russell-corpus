import { useState } from "react";
import { trpc } from "@/lib/trpc";
import { useAuth } from "@/_core/hooks/useAuth";
import { getLoginUrl } from "@/const";
import NavBar from "@/components/NavBar";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { toast } from "sonner";
import {
  Sparkles, CheckCircle, Circle, Moon, Dumbbell, Apple,
  Users, Brain, Heart, ChevronDown, ChevronUp, Activity
} from "lucide-react";

const CATEGORY_ICONS: Record<string, typeof Brain> = {
  Sleep: Moon, Exercise: Dumbbell, Nutrition: Apple,
  "Social Connection": Users, Mindfulness: Brain, Therapy: Heart,
};

const ACTION_TYPE_COLORS: Record<string, string> = {
  breathing_exercise: "text-blue-400 bg-blue-400/10 border-blue-400/30",
  gratitude_log: "text-yellow-400 bg-yellow-400/10 border-yellow-400/30",
  physical_activity: "text-orange-400 bg-orange-400/10 border-orange-400/30",
  sleep_routine: "text-indigo-400 bg-indigo-400/10 border-indigo-400/30",
  healthy_meal: "text-green-400 bg-green-400/10 border-green-400/30",
  social_interaction: "text-pink-400 bg-pink-400/10 border-pink-400/30",
  mindful_moment: "text-primary bg-primary/10 border-primary/30",
  therapy_reflection: "text-purple-400 bg-purple-400/10 border-purple-400/30",
};

const COMMON_DIAGNOSES = [
  "Major Depressive Disorder", "Generalized Anxiety Disorder", "PTSD",
  "Bipolar Disorder", "Social Anxiety Disorder", "Panic Disorder",
  "OCD", "ADHD", "Insomnia", "Adjustment Disorder",
];

export default function WellnessPlan() {
  const { isAuthenticated, loading } = useAuth();
  const [selectedDiagnoses, setSelectedDiagnoses] = useState<string[]>([]);
  const [expandedWeek, setExpandedWeek] = useState<number>(1);
  const [generating, setGenerating] = useState(false);

  const { data: activePlan, refetch: refetchPlan } = trpc.wellness.getActive.useQuery(undefined, {
    enabled: isAuthenticated,
  });

  const generatePlan = trpc.wellness.generate.useMutation({
    onMutate: () => setGenerating(true),
    onSuccess: () => {
      refetchPlan();
      setGenerating(false);
      toast.success("Your personalized 30-day wellness plan is ready!");
    },
    onError: () => {
      setGenerating(false);
      toast.error("Failed to generate plan. Please try again.");
    },
  });

  const markComplete = trpc.wellness.markActionComplete.useMutation({
    onSuccess: (data) => {
      refetchPlan();
      toast.success(`Action completed! Adherence: ${data.adherenceScore}%`);
    },
  });

  const toggleDiagnosis = (d: string) => {
    setSelectedDiagnoses(prev =>
      prev.includes(d) ? prev.filter(x => x !== d) : [...prev, d]
    );
  };

  if (loading) {
    return (
      <div className="min-h-screen bg-background">
        <NavBar />
        <div className="container py-24 flex justify-center">
          <div className="w-8 h-8 border-2 border-primary border-t-transparent rounded-full animate-spin" />
        </div>
      </div>
    );
  }

  if (!isAuthenticated) {
    return (
      <div className="min-h-screen bg-background">
        <NavBar />
        <div className="container py-24 max-w-md text-center">
          <Heart className="w-12 h-12 text-primary mx-auto mb-4" />
          <h2 className="text-2xl font-bold text-foreground mb-2">Sign In Required</h2>
          <p className="text-muted-foreground mb-6">Your wellness plan is personalized to your mental health profile.</p>
          <a href={getLoginUrl()}><Button className="bg-primary text-primary-foreground">Sign In</Button></a>
        </div>
      </div>
    );
  }

  const planData = activePlan?.planData as any;
  const weeks: any[] = planData?.weeks || [];
  const completedActions = (activePlan?.completedActions as string[]) || [];

  return (
    <div className="min-h-screen bg-background">
      <NavBar />
      <div className="container py-8 max-w-4xl">
        {/* Header */}
        <div className="mb-8">
          <div className="flex items-center gap-2 mb-2">
            <Heart className="w-5 h-5 text-primary" />
            <span className="text-sm text-muted-foreground font-medium">AI-Generated Personalized Plan</span>
          </div>
          <h1 className="text-2xl font-bold text-foreground mb-1">30-Day Wellness Plan</h1>
          <p className="text-muted-foreground text-sm">
            A structured, evidence-based daily action plan generated by AI based on your diagnoses and treatment goals.
          </p>
        </div>

        {!activePlan ? (
          /* Plan Generator */
          <Card className="border-border bg-card">
            <CardHeader>
              <CardTitle className="text-base font-semibold text-foreground flex items-center gap-2">
                <Sparkles className="w-4 h-4 text-primary" />
                Generate Your Plan
              </CardTitle>
            </CardHeader>
            <CardContent className="space-y-6">
              <div>
                <p className="text-sm text-foreground font-medium mb-3">Select your conditions (choose all that apply):</p>
                <div className="flex flex-wrap gap-2">
                  {COMMON_DIAGNOSES.map(d => (
                    <button
                      key={d}
                      onClick={() => toggleDiagnosis(d)}
                      className={`px-3 py-1.5 rounded-full text-xs font-medium border transition-all ${
                        selectedDiagnoses.includes(d)
                          ? "bg-primary/20 border-primary/50 text-primary"
                          : "border-border bg-secondary/20 text-muted-foreground hover:border-primary/30"
                      }`}
                    >
                      {d}
                    </button>
                  ))}
                </div>
              </div>

              {/* Category Preview */}
              <div>
                <p className="text-sm text-muted-foreground mb-3">Your plan will cover 6 wellness domains:</p>
                <div className="grid grid-cols-3 gap-2">
                  {Object.entries(CATEGORY_ICONS).map(([cat, Icon]) => (
                    <div key={cat} className="flex items-center gap-2 p-2 rounded-lg bg-secondary/20 border border-border">
                      <Icon className="w-4 h-4 text-primary" />
                      <span className="text-xs text-foreground">{cat}</span>
                    </div>
                  ))}
                </div>
              </div>

              <Button
                onClick={() => {
                  if (selectedDiagnoses.length === 0) {
                    toast.error("Please select at least one condition.");
                    return;
                  }
                  generatePlan.mutate({ diagnoses: selectedDiagnoses });
                }}
                disabled={generating || selectedDiagnoses.length === 0}
                className="w-full bg-primary text-primary-foreground glow-green-sm"
              >
                {generating ? (
                  <span className="flex items-center gap-2"><Sparkles className="w-4 h-4 animate-pulse" /> Generating your plan...</span>
                ) : (
                  <span className="flex items-center gap-2"><Sparkles className="w-4 h-4" /> Generate 30-Day Plan</span>
                )}
              </Button>
              {generating && (
                <p className="text-xs text-muted-foreground text-center animate-pulse">
                  AI is creating your personalized plan — this takes 10–20 seconds...
                </p>
              )}
            </CardContent>
          </Card>
        ) : (
          /* Active Plan View */
          <div className="space-y-6">
            {/* Plan Header */}
            <Card className="border-primary/30 bg-primary/5">
              <CardContent className="pt-4">
                <div className="flex items-start justify-between gap-4">
                  <div>
                    <h2 className="text-lg font-bold text-foreground mb-1">{activePlan.title}</h2>
                    <div className="flex flex-wrap gap-1.5 mb-3">
                      {(activePlan.diagnoses as string[])?.map(d => (
                        <Badge key={d} variant="outline" className="text-xs border-primary/30 text-primary">{d}</Badge>
                      ))}
                    </div>
                    <div className="flex items-center gap-4 text-sm">
                      <span className="text-muted-foreground">Adherence</span>
                      <div className="flex items-center gap-2">
                        <div className="w-32 h-2 bg-secondary/50 rounded-full overflow-hidden">
                          <div
                            className="h-full bg-primary rounded-full transition-all"
                            style={{ width: `${activePlan.adherenceScore || 0}%` }}
                          />
                        </div>
                        <span className="text-primary font-bold text-sm">{Math.round(activePlan.adherenceScore || 0)}%</span>
                      </div>
                    </div>
                  </div>
                  <Button
                    variant="outline"
                    size="sm"
                    className="border-border text-muted-foreground shrink-0"
                    onClick={() => generatePlan.mutate({ diagnoses: (activePlan.diagnoses as string[]) || [] })}
                  >
                    <Sparkles className="w-3.5 h-3.5 mr-1.5" /> New Plan
                  </Button>
                </div>
              </CardContent>
            </Card>

            {/* Weekly Themes */}
            {(activePlan.weeklyThemes as string[])?.length > 0 && (
              <div className="grid grid-cols-4 gap-2">
                {(activePlan.weeklyThemes as string[]).map((theme, i) => (
                  <button
                    key={i}
                    onClick={() => setExpandedWeek(i + 1)}
                    className={`p-3 rounded-lg border text-left transition-all ${
                      expandedWeek === i + 1
                        ? "border-primary/50 bg-primary/10"
                        : "border-border bg-card hover:border-primary/30"
                    }`}
                  >
                    <p className="text-xs text-muted-foreground mb-1">Week {i + 1}</p>
                    <p className="text-xs font-semibold text-foreground leading-snug">{theme}</p>
                  </button>
                ))}
              </div>
            )}

            {/* Week Detail */}
            {weeks.filter((w: any) => w.week === expandedWeek).map((week: any) => (
              <div key={week.week}>
                <h3 className="text-sm font-semibold text-foreground mb-3 flex items-center gap-2">
                  <Activity className="w-4 h-4 text-primary" />
                  Week {week.week}: {week.theme}
                </h3>
                <div className="grid md:grid-cols-2 gap-3">
                  {week.days?.map((day: any) => {
                    const dayCompleted = day.actions?.every((_: any, ai: number) => {
                      const key = `w${week.week}-d${day.day}-a${ai}`;
                      return completedActions.includes(key);
                    });
                    return (
                      <Card key={day.day} className={`border-border bg-card ${dayCompleted ? "opacity-60" : ""}`}>
                        <CardHeader className="pb-2">
                          <CardTitle className="text-xs font-semibold text-muted-foreground flex items-center justify-between">
                            Day {day.day}
                            {dayCompleted && <CheckCircle className="w-4 h-4 text-primary" />}
                          </CardTitle>
                        </CardHeader>
                        <CardContent className="space-y-2">
                          {day.actions?.map((action: any, ai: number) => {
                            const key = `w${week.week}-d${day.day}-a${ai}`;
                            const done = completedActions.includes(key);
                            const colorClass = ACTION_TYPE_COLORS[action.type] || "text-muted-foreground bg-secondary/20 border-border";
                            return (
                              <div key={ai} className={`flex items-start gap-2 p-2 rounded-lg border ${done ? "opacity-50" : colorClass}`}>
                                <button
                                  onClick={() => !done && markComplete.mutate({ planId: activePlan.id, actionKey: key })}
                                  className="shrink-0 mt-0.5"
                                  disabled={done}
                                >
                                  {done
                                    ? <CheckCircle className="w-4 h-4 text-primary" />
                                    : <Circle className="w-4 h-4 text-muted-foreground hover:text-primary transition-colors" />
                                  }
                                </button>
                                <div className="flex-1 min-w-0">
                                  <p className="text-xs font-semibold text-foreground">{action.title}</p>
                                  <p className="text-[11px] text-muted-foreground leading-snug mt-0.5">{action.description}</p>
                                  <span className="text-[10px] text-muted-foreground">{action.durationMinutes} min</span>
                                </div>
                              </div>
                            );
                          })}
                        </CardContent>
                      </Card>
                    );
                  })}
                </div>
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}

/**
 * Clinical PDF Export Utility
 * Generates a formatted clinical report PDF using jsPDF
 * Used by DiagnosticReport page for one-click provider export
 */

import jsPDF from "jspdf";

export interface ClinicalReportData {
  reportId: number;
  patientName?: string;
  generatedAt: Date;
  provisionalDiagnoses: Array<{ condition: string; icdCode?: string; confidence?: string; rationale?: string }>;
  prsScore?: number;
  prsBreakdown?: Record<string, number>;
  treatmentRecommendations?: Array<{
    category: string;
    title: string;
    description: string;
    evidenceLevel: string;
    citations: string[];
  }>;
}

export function exportClinicalReportPDF(data: ClinicalReportData): void {
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const pageW = 210;
  const margin = 20;
  const contentW = pageW - margin * 2;
  let y = 20;

  // ─── Helper functions ────────────────────────────────────────────────────────
  const addPage = () => {
    doc.addPage();
    y = 20;
  };

  const checkPageBreak = (needed = 20) => {
    if (y + needed > 270) addPage();
  };

  const drawHRule = (color = "#e2e8f0") => {
    doc.setDrawColor(color);
    doc.setLineWidth(0.3);
    doc.line(margin, y, pageW - margin, y);
    y += 4;
  };

  const addText = (
    text: string,
    opts: { size?: number; bold?: boolean; color?: string; indent?: number; wrap?: boolean } = {}
  ) => {
    const { size = 10, bold = false, color = "#1e293b", indent = 0, wrap = false } = opts;
    doc.setFontSize(size);
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.setTextColor(color);
    if (wrap) {
      const lines = doc.splitTextToSize(text, contentW - indent);
      checkPageBreak(lines.length * (size * 0.4 + 1.5));
      doc.text(lines, margin + indent, y);
      y += lines.length * (size * 0.4 + 1.5);
    } else {
      checkPageBreak(size * 0.4 + 2);
      doc.text(text, margin + indent, y);
      y += size * 0.4 + 2;
    }
  };

  const addSection = (title: string) => {
    checkPageBreak(14);
    y += 4;
    doc.setFillColor("#0f172a");
    doc.roundedRect(margin, y - 5, contentW, 10, 2, 2, "F");
    doc.setFontSize(11);
    doc.setFont("helvetica", "bold");
    doc.setTextColor("#ffffff");
    doc.text(title.toUpperCase(), margin + 4, y + 1.5);
    y += 10;
    doc.setTextColor("#1e293b");
  };

  // ─── Header ──────────────────────────────────────────────────────────────────
  // Logo bar
  doc.setFillColor("#0f172a");
  doc.rect(0, 0, pageW, 30, "F");

  doc.setFontSize(18);
  doc.setFont("helvetica", "bold");
  doc.setTextColor("#ffffff");
  doc.text("Dr. Buddy", margin, 13);

  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.setTextColor("#94a3b8");
  doc.text("AI-Powered Psychiatric Assessment Platform", margin, 20);
  doc.text("Doctor Buddy · Clinical Decision Support", margin, 26);

  // Report title
  doc.setFontSize(9);
  doc.setTextColor("#94a3b8");
  doc.text(`Report #${data.reportId}`, pageW - margin - 30, 13);
  doc.text(
    `Generated: ${data.generatedAt.toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })}`,
    pageW - margin - 50,
    20
  );

  y = 38;

  // ─── Disclaimer ──────────────────────────────────────────────────────────────
  doc.setFillColor("#fef3c7");
  doc.roundedRect(margin, y, contentW, 16, 2, 2, "F");
  doc.setFontSize(8);
  doc.setFont("helvetica", "bold");
  doc.setTextColor("#92400e");
  doc.text("⚠  CLINICAL DISCLAIMER", margin + 4, y + 5);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);
  const disclaimer =
    "This report is generated by an AI system and is intended as a clinical decision-support tool only. It does not constitute a formal psychiatric diagnosis. All findings must be reviewed and validated by a licensed mental health professional before any clinical decisions are made.";
  const dLines = doc.splitTextToSize(disclaimer, contentW - 8);
  doc.text(dLines, margin + 4, y + 10);
  y += 20;

  // ─── Patient & Report Info ────────────────────────────────────────────────────
  addSection("Patient & Report Information");
  y += 2;

  const infoRows = [
    ["Patient", data.patientName || "Confidential"],
    ["Report ID", `#${data.reportId}`],
    ["Assessment Date", data.generatedAt.toLocaleDateString("en-US", { weekday: "long", year: "numeric", month: "long", day: "numeric" })],
    ["Platform", "Doctor Buddy AI Psychiatric Assessment"],
    ["Assessment Type", "Adaptive DSM-5 Intake (41–100 questions, 11 gateway rules)"],
  ];

  infoRows.forEach(([label, value]) => {
    checkPageBreak(8);
    doc.setFontSize(9);
    doc.setFont("helvetica", "bold");
    doc.setTextColor("#475569");
    doc.text(label + ":", margin, y);
    doc.setFont("helvetica", "normal");
    doc.setTextColor("#1e293b");
    doc.text(value, margin + 45, y);
    y += 7;
  });

  // ─── Psychiatric Risk Score ───────────────────────────────────────────────────
  if (data.prsScore !== undefined) {
    addSection("Psychiatric Risk Score™ (PRS)");
    y += 2;

    const band =
      data.prsScore >= 800
        ? { label: "Optimal", color: "#059669" }
        : data.prsScore >= 600
        ? { label: "Resilient", color: "#0284c7" }
        : data.prsScore >= 400
        ? { label: "Moderate Risk", color: "#d97706" }
        : data.prsScore >= 200
        ? { label: "High Risk", color: "#dc2626" }
        : { label: "Critical Risk", color: "#7f1d1d" };

    // Score box
    doc.setFillColor(band.color);
    doc.roundedRect(margin, y, 50, 20, 3, 3, "F");
    doc.setFontSize(22);
    doc.setFont("helvetica", "bold");
    doc.setTextColor("#ffffff");
    doc.text(String(data.prsScore), margin + 8, y + 13);

    doc.setFontSize(10);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(band.color);
    doc.text(band.label, margin + 56, y + 8);
    doc.setFontSize(8.5);
    doc.setFont("helvetica", "normal");
    doc.setTextColor("#475569");
    doc.text("Score range: 0 (Critical) → 1000 (Optimal)", margin + 56, y + 15);
    y += 26;

    // Domain breakdown if available
    if (data.prsBreakdown && Object.keys(data.prsBreakdown).length > 0) {
      addText("Domain Breakdown:", { bold: true, size: 9, color: "#475569" });
      y += 1;
      const domains = Object.entries(data.prsBreakdown).slice(0, 8);
      domains.forEach(([domain, score]) => {
        checkPageBreak(8);
        const barW = Math.round(((score as number) / 100) * (contentW - 60));
        const barColor = (score as number) >= 70 ? "#059669" : (score as number) >= 40 ? "#d97706" : "#dc2626";
        doc.setFontSize(8.5);
        doc.setFont("helvetica", "normal");
        doc.setTextColor("#475569");
        doc.text(domain.replace(/([A-Z])/g, " $1").trim(), margin, y);
        doc.setFillColor("#e2e8f0");
        doc.roundedRect(margin + 55, y - 4, contentW - 60, 5, 1, 1, "F");
        doc.setFillColor(barColor);
        doc.roundedRect(margin + 55, y - 4, Math.max(barW, 2), 5, 1, 1, "F");
        doc.setFontSize(8);
        doc.setTextColor("#1e293b");
        doc.text(`${score}`, pageW - margin - 8, y);
        y += 7;
      });
    }
  }

  // ─── Provisional Diagnoses ────────────────────────────────────────────────────
  addSection("Provisional Diagnoses");
  y += 2;

  if (!data.provisionalDiagnoses || data.provisionalDiagnoses.length === 0) {
    addText("No provisional diagnoses generated.", { color: "#64748b", size: 9 });
  } else {
    data.provisionalDiagnoses.forEach((dx, i) => {
      checkPageBreak(30);
      // Diagnosis header
      doc.setFillColor(i === 0 ? "#eff6ff" : "#f8fafc");
      doc.roundedRect(margin, y, contentW, 8, 2, 2, "F");
      doc.setFontSize(10);
      doc.setFont("helvetica", "bold");
      doc.setTextColor("#1e40af");
      doc.text(`${i + 1}. ${dx.condition}`, margin + 4, y + 5.5);
      if (dx.icdCode) {
        doc.setFontSize(8.5);
        doc.setFont("helvetica", "normal");
        doc.setTextColor("#64748b");
        doc.text(dx.icdCode, pageW - margin - 20, y + 5.5);
      }
      y += 11;

      if (dx.confidence) {
        addText(`Confidence: ${dx.confidence}`, { size: 8.5, color: "#475569", indent: 4 });
      }
      if (dx.rationale) {
        addText(dx.rationale, { size: 8.5, color: "#374151", indent: 4, wrap: true });
      }
      y += 3;
    });
  }

  // ─── Treatment Recommendations ────────────────────────────────────────────────
  if (data.treatmentRecommendations && data.treatmentRecommendations.length > 0) {
    addSection("Evidence-Based Treatment Recommendations");
    y += 2;

    const categoryColors: Record<string, string> = {
      pharmacotherapy: "#7c3aed",
      psychotherapy: "#0284c7",
      lifestyle: "#059669",
      referral: "#d97706",
    };

    data.treatmentRecommendations.forEach((rec, i) => {
      checkPageBreak(35);
      const catColor = categoryColors[rec.category] || "#475569";

      // Rec header bar
      doc.setFillColor("#f8fafc");
      doc.roundedRect(margin, y, contentW, 9, 2, 2, "F");
      doc.setFontSize(9.5);
      doc.setFont("helvetica", "bold");
      doc.setTextColor("#1e293b");
      doc.text(`${i + 1}. ${rec.title}`, margin + 4, y + 6);

      // Category badge
      doc.setFillColor(catColor);
      const catLabel = rec.category.charAt(0).toUpperCase() + rec.category.slice(1);
      doc.roundedRect(pageW - margin - 35, y + 1.5, 33, 6, 2, 2, "F");
      doc.setFontSize(7.5);
      doc.setFont("helvetica", "bold");
      doc.setTextColor("#ffffff");
      doc.text(catLabel, pageW - margin - 33, y + 6);

      y += 12;

      // Evidence level
      const evColor = rec.evidenceLevel === "A" ? "#059669" : rec.evidenceLevel === "B" ? "#d97706" : "#64748b";
      doc.setFontSize(8);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(evColor);
      doc.text(`Evidence Level ${rec.evidenceLevel}`, margin + 4, y);
      y += 5;

      // Description
      addText(rec.description, { size: 8.5, color: "#374151", indent: 4, wrap: true });

      // Citations
      if (rec.citations && rec.citations.length > 0) {
        addText(`References: ${rec.citations.slice(0, 3).join(" · ")}`, {
          size: 7.5,
          color: "#64748b",
          indent: 4,
          wrap: true,
        });
      }
      y += 4;
      drawHRule("#f1f5f9");
    });
  }

  // ─── Footer on every page ─────────────────────────────────────────────────────
  const totalPages = (doc as any).internal.getNumberOfPages();
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p);
    doc.setFillColor("#f8fafc");
    doc.rect(0, 285, pageW, 12, "F");
    doc.setFontSize(7.5);
    doc.setFont("helvetica", "normal");
    doc.setTextColor("#94a3b8");
    doc.text("Doctor Buddy · AI-Assisted Clinical Decision Support · Not a substitute for professional diagnosis", margin, 292);
    doc.text(`Page ${p} of ${totalPages}`, pageW - margin - 15, 292);
  }

  // ─── Save ─────────────────────────────────────────────────────────────────────
  const filename = `DrBuddy_Report_${data.reportId}_${data.generatedAt.toISOString().slice(0, 10)}.pdf`;
  doc.save(filename);
}

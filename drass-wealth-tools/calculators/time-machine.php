/**
 * Time Machine — the dual view.
 *
 * Two panels from one engine:
 *
 *   1. The AG 49 illustration. A flat compliant crediting rate, forward.
 *   2. The historical disclosure. The same policy's floor, cap and
 *      participation applied to actual index history, backwards.
 *
 * Panel 2 is not a bolt-on and not a workaround. AG 49 and AG 49-A require a
 * capped-and-floored historical disclosure with a 25-year lookback alongside
 * the illustration. Showing it is the rule, not an exception to the rule. The
 * only thing that changed in November 2025 is that a *constructed* comparison
 * built to imply the historical result is what the buyer should expect became
 * prohibited — which is why nothing here presents panel 2 as an expectation,
 * and why no geometric average is printed.
 *
 * Both panels are generated by the same engine call, so they cannot disagree
 * with each other. That is the part worth claiming: a single source producing
 * both the compliant projection and its required disclosure removes the class
 * of error where the two exhibits are computed separately and drift apart.
 *
 * The disclosure mode is an owner-set option, not a decision made here. See
 * DWT_Compliance and the note in INSTALL.md. Whoever signs off on the firm's
 * advertising compliance sets it; this file obeys it.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

function dwt_render_time_machine( $atts = [] ): string {
	$a = shortcode_atts( [
		'premium'        => '25000',
		'funding_years'  => '5',
		'age'            => '45',
		'years'          => '30',
		'ag49_rate'      => '6.0',
		'index'          => 'SP500',
		'start_year'     => '1994',
	], $atts, 'dwt_time_machine' );

	wp_enqueue_style( 'dwt' );

	$res = DWT_API::get( 'api/time-machine', [
		'premium'       => (string) absint( $a['premium'] ),
		'fundingYears'  => (string) absint( $a['funding_years'] ),
		'age'           => (string) absint( $a['age'] ),
		'years'         => (string) absint( $a['years'] ),
		'ag49Rate'      => (string) (float) $a['ag49_rate'],
		'index'         => sanitize_text_field( $a['index'] ),
		'startYear'     => (string) absint( $a['start_year'] ),
	] );

	if ( is_wp_error( $res ) ) {
		return DWT_Shortcodes::render_refusal( $res );
	}

	$illustration = isset( $res['boring'] ) && is_array( $res['boring'] ) ? $res['boring'] : [];
	$historical   = isset( $res['historical'] ) && is_array( $res['historical'] ) ? $res['historical'] : [];

	if ( ! $illustration || ! $historical ) {
		return DWT_Shortcodes::render_refusal(
			'The calculation service did not return both panels. Rather than show one of the two, this tool shows neither — an illustration without its required historical disclosure is not a complete exhibit.'
		);
	}

	// The gate. constructed_comparison stays false: this is the disclosure the
	// guideline prescribes, generated from the same engine as the illustration
	// it accompanies, and it is not presented as an expectation.
	$ok = DWT_Compliance::guard_historical( [
		'mode'                   => DWT_Compliance::MODE_EDUCATIONAL,
		'index_age_years'        => (int) ( $res['indexAgeYears'] ?? count( $historical ) ),
		'years_shown'            => count( $historical ),
		'alongside_illustration' => false,
	] );
	if ( is_wp_error( $ok ) ) {
		return DWT_Shortcodes::render_refusal( $ok );
	}

	$money = static function ( $n ): string {
		return '$' . number_format( (float) $n, 0 );
	};

	$out  = '<div class="dwt dwt-tm">';
	$out .= DWT_Compliance::historical_notice_html();

	$out .= '<div class="dwt-panels">';

	// ── Panel 1: the AG 49 illustration ────────────────────────────────────
	$out .= '<section class="dwt-panel"><h3 class="dwt-panel-h">Illustration</h3>';
	$out .= '<p class="dwt-panel-sub">' . esc_html(
		sprintf( 'Projected forward at a level %s%% crediting rate, within the AG 49 maximum illustrated rate.', number_format( (float) $a['ag49_rate'], 2 ) )
	) . '</p>';
	$out .= '<div class="dwt-tablewrap"><table class="dwt-table"><thead><tr>'
		. '<th scope="col">Year</th><th scope="col">Account value</th><th scope="col">Surrender value</th>'
		. '</tr></thead><tbody>';
	foreach ( $illustration as $r ) {
		$out .= '<tr><th scope="row">' . esc_html( (string) (int) ( $r['year'] ?? 0 ) ) . '</th>'
			. '<td>' . esc_html( $money( $r['accountValue'] ?? 0 ) ) . '</td>'
			. '<td>' . esc_html( $money( $r['surrenderValue'] ?? 0 ) ) . '</td></tr>';
	}
	$out .= '</tbody></table></div>';
	$out .= '<p class="dwt-foot">' . esc_html(
		'Non-guaranteed. Projected values assume the level rate shown is credited every year, which no policy has ever done.'
	) . '</p></section>';

	// ── Panel 2: the required historical disclosure ────────────────────────
	$out .= '<section class="dwt-panel"><h3 class="dwt-panel-h">Historical disclosure</h3>';
	$out .= '<p class="dwt-panel-sub">' . DWT_Compliance::would_have_been_caption() . '</p>';
	$out .= '<div class="dwt-tablewrap"><table class="dwt-table"><thead><tr>'
		. '<th scope="col">Year</th><th scope="col">Index change</th>'
		. '<th scope="col">Credited</th><th scope="col">Account value</th>'
		. '</tr></thead><tbody>';
	foreach ( $historical as $r ) {
		$change   = (float) ( $r['indexChange'] ?? 0 );
		$credited = (float) ( $r['creditedRate'] ?? 0 );
		$negative = $change < 0;
		$out .= '<tr' . ( $negative ? ' class="dwt-row--floor"' : '' ) . '>';
		$out .= '<th scope="row">' . esc_html( (string) (int) ( $r['calendarYear'] ?? $r['year'] ?? 0 ) ) . '</th>';
		$out .= '<td>' . esc_html( number_format( $change, 2 ) ) . '%</td>';
		$out .= '<td class="dwt-credited">' . esc_html( number_format( $credited, 2 ) ) . '%';
		if ( $negative ) {
			$out .= ' <span class="dwt-tag dwt-tag--floor">floor held</span>';
		}
		$out .= '</td>';
		$out .= '<td>' . esc_html( $money( $r['accountValue'] ?? 0 ) ) . '</td></tr>';
	}
	$out .= '</tbody></table></div>';
	$out .= '<p class="dwt-foot">' . esc_html(
		'What would have been credited had these rates been applied to actual historical index changes. This is a record of the past, not a forecast. Cap and participation rates are not guaranteed for the life of a policy and have changed materially over time.'
	) . '</p></section>';

	$out .= '</div>';

	// Deliberately absent: any sentence inviting the reader to treat the
	// historical panel as what to expect, and any geometric average. Both are
	// what the November 2025 amendment exists to stop.
	$out .= '</div>';

	return $out;
}

/**
 * Provenance census — writes the report the CI ratchet asserts against.
 *
 *   npx tsx scripts/provenance-census.ts            → docs/provenance/
 *   npx tsx scripts/provenance-census.ts --out DIR
 *
 * The counts come from server/_core/provenanceCensus.ts, the same code the
 * test runs; re-running on the same tree regenerates the files identically.
 * Never prints an environment value, never reproduces a formula.
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { censusTree } from "../server/_core/provenanceCensus";

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(arg("root") ?? path.join(HERE, ".."));
const OUT = path.resolve(arg("out") ?? path.join(ROOT, "docs/provenance"));
const TREE_SHA = (() => { try { return execSync("git rev-parse --short HEAD", { cwd: ROOT, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch { return "unknown"; } })();

const { rows, summary } = censusTree(ROOT);
mkdirSync(OUT, { recursive: true });

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const cell = (arr: string[], max = 4) => arr.length === 0 ? "none" : esc(arr.slice(0, max).join("; ")) + (arr.length > max ? ` (+${arr.length - max})` : "");
const list = (arr: string[]) => (arr.length ? arr.map(e => `- \`${e}\``).join("\n") : "- none");

const md: string[] = [];
md.push(`# Provenance census — tree \`${TREE_SHA}\``, "");
md.push("Generated by `scripts/provenance-census.ts` from `server/_core/provenanceCensus.ts`; `server/provenanceCensus.test.ts` asserts these lists only shrink. One row per engine registered in `shared/calculatorCatalog.ts` (`engine:`) or `shared/aiMemoryBank.ts` (`modules`).", "");
md.push("`sources: none` means the file names no institution, URL, dated source or exported `*_SOURCES` constant: the value is typed in. `Shell` means the app shell prints the engine's own source list under every catalogue page that uses it (`shared/engineSources.ts`).", "");
md.push("| # | Engine | Catalogue pages | Pages importing | Sources | Source exports | Simulation | Live feed | Provenance on page | Shell |");
md.push("|---|---|---|---|---|---|---|---|---|---|");
rows.forEach((r, i) => {
  const sim = r.simulation.markers.length === 0 && !r.simulation.unseededRandom ? "none" : [
    r.simulation.markers.join(", "),
    r.simulation.runs.length ? `runs ${r.simulation.runs.join("/")}` : "",
    r.simulation.seeds.length ? `seed ${r.simulation.seeds.join("/")}` : "",
    r.simulation.unseededRandom ? "**Math.random (unseeded)**" : r.simulation.seeded ? "seeded" : "",
  ].filter(Boolean).join("; ");
  md.push(`| ${i + 1} | \`${r.engine}\`${r.exists ? "" : " **(missing on disk)**"} | ${r.cataloguePages.length ? esc(r.cataloguePages.join(", ")) : "—"} | ${r.pages.length}${r.serverImporters.length ? ` (+${r.serverImporters.length} server)` : ""} | ${r.sources.length === 0 ? "**none**" : cell(r.sources, 3)} | ${cell(r.sourceExports, 3)} | ${esc(sim)} | ${cell(r.liveFeed, 4)} | ${r.pages.length === 0 ? "no page" : r.provenanceOnPage ? `yes (${r.provenancePages.length}/${r.pages.length})` : "**no**"} | ${r.shellSourced ? "yes" : r.cataloguePages.length ? "**no**" : "—"} |`);
});
writeFileSync(path.join(OUT, "PROVENANCE_CENSUS.md"), md.join("\n") + "\n");

const sm: string[] = [];
sm.push(`# Provenance census — summary (tree \`${TREE_SHA}\`)`, "");
sm.push("Every count below is computed from the tree; none is typed. `server/provenanceCensus.test.ts` fails the build if any list grows.", "");
sm.push("| Count | Value |", "|---|---|");
sm.push(`| Engines censused | ${summary.engines} (${summary.enginesFromCatalogue} via catalogue bindings, ${summary.enginesFromMemoryBank} via memory-bank modules, union) |`);
sm.push(`| **Engines with zero sources** | **${summary.counts.enginesWithZeroSources}** (of which ${summary.counts.numericEnginesWithZeroSources} carry 20+ typed-in numeric literals) |`);
sm.push(`| **Catalogue engines whose sources the shell cannot print yet** | **${summary.counts.enginesWithoutShellSources}** |`);
sm.push(`| **Engines with unseeded randomness** | **${summary.counts.enginesWithUnseededRandomness}** |`);
sm.push(`| **Pages that import an engine and print no source** | **${summary.counts.pagesImportingAnEngineWithNoProvenanceOnPage}** of ${summary.counts.pagesImportingAnEngine} |`);
sm.push(`| Engines with hard-coded years older than 2025 | ${summary.counts.enginesWithHardCodedYearsOlderThan2025} |`);
sm.push(`| Engines that simulate | ${summary.counts.enginesThatSimulate} |`);
sm.push(`| Engines on a live feed seam | ${summary.counts.enginesOnALiveFeed} |`);
sm.push(`| Engines imported by no page and no router | ${summary.counts.enginesImportedByNoPageAndNoRouter} |`);
sm.push("", "## Engines with zero sources", "", list(summary.lists.enginesWithZeroSources));
sm.push("", "## Catalogue engines whose sources the shell cannot print yet", "", list(summary.lists.enginesWithoutShellSources));
sm.push("", "## Engines with unseeded randomness", "", list(summary.lists.enginesWithUnseededRandomness));
sm.push("", "## Pages that import an engine and print no source", "", list(summary.lists.pagesImportingAnEngineWithNoProvenanceOnPage));
sm.push("", "## Engines with hard-coded years older than 2025", "", list(summary.lists.enginesWithHardCodedYearsOlderThan2025));
sm.push("", "## What this census does not contain", "", "- No environment values, keys, private hostnames or vault material.", "- No method claims: formulas, coefficients, weightings and step order are not described.", "- No client data.");
writeFileSync(path.join(OUT, "SUMMARY.md"), sm.join("\n") + "\n");
writeFileSync(path.join(OUT, "provenance-census.json"), JSON.stringify({ tree: TREE_SHA, summary, rows }, null, 2) + "\n");

console.log(JSON.stringify({ out: OUT, tree: TREE_SHA, ...summary.counts }, null, 2));

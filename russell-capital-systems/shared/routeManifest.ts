// ─── Route manifest ─────────────────────────────────────────────────────────
//
// Every route the application serves, one per line.
//
// ## Why this replaced an integer
//
// Two smoke tests used to assert `expect(currentRoutes.size).toBe(N)`. That
// integer was the single most reliable merge conflict in the repository: any
// two branches that each added a route collided on it, every time, and the
// resolution was always the sum of both sides rather than either side's number
// — which is a merge a machine should do and a human kept doing by hand.
//
// A list does not collide. Two branches adding different routes produce two
// non-overlapping line insertions, and git merges them without help.
//
// It also catches what a count cannot. A count passes when one route is
// deleted and another added in the same change; the manifest shows exactly
// which line moved. And a duplicate route — the same path registered twice —
// is invisible to `.size` because a Set swallows it, but visible here.
//
// ## Keeping it current
//
// Adding a route means adding its path here. The smoke tests compare this list
// against the routes actually registered in App.tsx and fail with the specific
// paths that differ, in both directions, so the fix is always named.
//
// Generated from client/src/App.tsx on 2026-09-18; maintained by hand thereafter.


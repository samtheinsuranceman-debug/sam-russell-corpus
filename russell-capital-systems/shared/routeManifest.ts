/** Paths registered but absent from the manifest, and vice versa. */
export function diffRoutes(actual: Iterable<string>): { missing: string[]; unexpected: string[]; duplicates: string[] } {
  const actualList: string[] = [];
  const it = actual as Iterable<string>;
  for (const a of Array.from(it)) actualList.push(a);
  const seen: Record<string, number> = {};
  for (let i = 0; i < actualList.length; i++) seen[actualList[i]] = (seen[actualList[i]] || 0) + 1;
  const duplicates = Object.keys(seen).filter((k) => seen[k] > 1).sort();
  const declared: Record<string, true> = {};
  for (let i = 0; i < ROUTE_MANIFEST.length; i++) declared[ROUTE_MANIFEST[i]] = true;
  const present: Record<string, true> = {};
  for (let i = 0; i < actualList.length; i++) present[actualList[i]] = true;
  const missing = ROUTE_MANIFEST.filter((r) => !present[r]).sort();
  const unexpected = Object.keys(present).filter((r) => !declared[r]).sort();
  return { missing, unexpected, duplicates };
}

// ============================================================
// PATENT BENCHMARK + PROTOTYPE-DEMONSTRATION HARNESS.
// Run on demand:
//   npx vitest run --config vitest.audit.config.ts scripts/patentBenchmarks.test.ts
// Measures the IMPLEMENTED software embodiments of the JoinAQAL
// patent engines on this machine and writes two filing-support
// documents with real, reproduced numbers:
//   docs/PATENT_BENCHMARKS.md
//   docs/PATENT_PROTOTYPE_DEMONSTRATION.md
// Honesty: these are software-embodiment numbers on commodity
// container hardware, labeled as such — NOT hardware co-processor
// claims. Every figure is regenerated by rerunning this harness.
// ============================================================
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { performance } from "node:perf_hooks";
import { describe, expect, it } from "vitest";
import { calibratedConsensus, equalWeights, type ModelAxisScores } from "../server/patents/calibrationBus";
import { entryHash, verifyChain, GENESIS_HASH, type LedgerRow } from "../server/patents/ledger";
import { extractVoiceFeatures } from "../server/patents/voiceFeatures";
import { controllingWeakness } from "../server/scoring/controllingWeakness";
import { multiplicativeRarity } from "../server/scoring/multiplicativeRarity";
import { softwareFabric } from "../server/patents/computeFabric";
import { isolateDimensions } from "../server/patents/dimensionIsolation";
import { SISTER_COMBINATIONS } from "../server/patents/combinations/registry";
import * as combinators from "../server/patents/combinations/index";
import { ALL_AXES } from "../shared/axisModes";

const ms = (t: number) => `${t.toFixed(2)} ms`;

function synthPanel(models: number, spread = 0.08): ModelAxisScores[] {
  return Array.from({ length: models }, (_, m) => ({
    model: `model_${m}`,
    scores: ALL_AXES.map((name, i) => ({
      axisIndex: i, axisName: name,
      score: Math.min(1, Math.max(0, 0.55 + Math.sin(i * 1.7 + m) * spread)),
      confidence: 0.8,
    })),
  }));
}

function sine(freq: number, seconds: number, sr = 16000): Float32Array {
  const n = Math.floor(seconds * sr);
  const pcm = new Float32Array(n);
  for (let i = 0; i < n; i++) pcm[i] = 0.5 * Math.sin((2 * Math.PI * freq * i) / sr);
  return pcm;
}

describe("patent benchmarks + prototype demonstration", () => {
  it("measures every implemented engine and writes the filing-support docs", async () => {
    const bench: string[] = [];
    const demo: string[] = [];

    // ── 1. Consensus engine (PAT-001) ──────────────────────────────────────
    const panel = synthPanel(8);
    let t0 = performance.now();
    const RUNS = 2000;
    let consensus = calibratedConsensus(panel, equalWeights);
    for (let i = 1; i < RUNS; i++) consensus = calibratedConsensus(panel, equalWeights);
    const consensusMs = (performance.now() - t0) / RUNS;
    bench.push(`| 8-model × 32-line consensus combine | ${ms(consensusMs)} per full combine | ${Math.round(1000 / consensusMs).toLocaleString()} combines/sec |`);
    demo.push(`### Consensus engine (PAT-001)\n8 synthetic models scored 32 lines with deliberate disagreement; the calibration-weighted trimmed consensus settled line 0 ("${consensus[0].axisName}") at ${consensus[0].score.toFixed(4)} with confidence ${consensus[0].confidence.toFixed(3)} — reasoning emitted: "${consensus[0].reasoning}"`);
    expect(consensus).toHaveLength(32);

    // ── 2. Voice feature extraction (PAT-002) ──────────────────────────────
    const audio = sine(220, 30);
    t0 = performance.now();
    const vf = await extractVoiceFeatures(audio, 16000, "a thirty second synthetic answer used for timing");
    const voiceMs = performance.now() - t0;
    const acc: string[] = [];
    for (const f of [110, 220, 330]) {
      const r = await extractVoiceFeatures(sine(f, 1.0), 16000);
      acc.push(`${f} Hz→${r.pitchMeanHz.toFixed(1)} Hz (${(100 * Math.abs(r.pitchMeanHz - f) / f).toFixed(1)}% err)`);
      expect(Math.abs(r.pitchMeanHz - f) / f).toBeLessThan(0.1);
    }
    bench.push(`| Voice feature extraction (30 s audio, full pipeline) | ${ms(voiceMs)} | ${(30_000 / voiceMs).toFixed(0)}× faster than real time |`);
    bench.push(`| Pitch recovery accuracy (synthetic tones) | ${acc.join("; ")} | all within 10% |`);
    demo.push(`### Voice-feature engine (PAT-002)\n30 s of synthetic audio produced: pitchMean ${vf.pitchMeanHz.toFixed(1)} Hz, rmsEnergy ${vf.rmsEnergyMean.toFixed(3)}, pauses ${vf.pauseCount}, speakingRate ${vf.speakingRateWPM.toFixed(1)} WPM. Tone-accuracy: ${acc.join("; ")}.`);

    // ── 3. Ledger (shared component 1) ─────────────────────────────────────
    const N = 10_000;
    t0 = performance.now();
    const rows: LedgerRow[] = [];
    let prev = GENESIS_HASH;
    for (let i = 0; i < N; i++) {
      const payload = { assessmentId: i, axes: [{ i: i % 32, s: (i % 100) / 100 }] };
      const hash = entryHash(prev, "score", payload);
      rows.push({ id: i + 1, kind: "score", payload, prevHash: prev, hash });
      prev = hash;
    }
    const appendMs = performance.now() - t0;
    t0 = performance.now();
    const verdict = verifyChain(rows);
    const verifyMs = performance.now() - t0;
    expect(verdict.valid).toBe(true);
    bench.push(`| Ledger: hash-chain ${N.toLocaleString()} entries | ${ms(appendMs)} (${Math.round(N / (appendMs / 1000)).toLocaleString()} appends/sec) | full-chain verify ${ms(verifyMs)} |`);
    const tampered = rows.map((r, i) => (i === 5000 ? { ...r, payload: { hacked: true } } : r));
    const caught = verifyChain(tampered);
    expect(caught.valid).toBe(false);
    demo.push(`### Immutable ledger\n${N.toLocaleString()} chained entries built and verified valid in ${ms(verifyMs)}. A single payload edit at entry 5001 was then detected at exactly id ${caught.badId}.`);

    // ── 4. Controlling weakness (PAT-004) ──────────────────────────────────
    const vec = ALL_AXES.map((_, i) => 0.5 + (i % 7) * 0.05); vec[19] = 0.11;
    t0 = performance.now();
    const ITER = 200_000;
    let cw = controllingWeakness(vec)!;
    for (let i = 1; i < ITER; i++) cw = controllingWeakness(vec)!;
    const cwUs = ((performance.now() - t0) / ITER) * 1000;
    bench.push(`| Controlling-weakness argmin (32-line vector) | ${cwUs.toFixed(2)} µs/op | ${Math.round(1_000_000 / cwUs).toLocaleString()} ops/sec |`);
    demo.push(`### Controlling-weakness engine (PAT-004)\nGiven a 32-line vector with a planted minimum, the argmin returned axis ${cw.axisIndex} ("${cw.axisName}") at ${cw.score} with constraint impact ${cw.constraintImpact.toFixed(3)}.`);
    expect(cw.axisIndex).toBe(19);

    // ── 5. Multiplicative rarity (AQAL-002, unwired engine) ────────────────
    const scores32 = ALL_AXES.map((n, i) => ({ axisIndex: i, axisName: n, score: 0.62 }));
    t0 = performance.now();
    for (let i = 0; i < 50_000; i++) multiplicativeRarity(scores32, [{ axisIndex: 0, floor: 0.7 }]);
    const rarUs = ((performance.now() - t0) / 50_000) * 1000;
    bench.push(`| Floor-gated multiplicative rarity (32 lines) | ${rarUs.toFixed(2)} µs/op | engine benchmarked; deliberately unwired from display |`);

    // ── 6. Compute fabric parallel speedup ─────────────────────────────────
    const task = () => new Promise<number>((r) => setTimeout(() => r(1), 25));
    t0 = performance.now();
    for (let i = 0; i < 8; i++) await task();
    const serialMs = performance.now() - t0;
    t0 = performance.now();
    await softwareFabric.runParallel(Array.from({ length: 8 }, (_, i) => i), task, { concurrency: 8 });
    const parMs = performance.now() - t0;
    bench.push(`| Compute fabric: 8 × 25 ms tasks | serial ${ms(serialMs)} → parallel ${ms(parMs)} | ${(serialMs / parMs).toFixed(1)}× speedup (software backend) |`);
    demo.push(`### Compute fabric\nThe same 8-task workload ran ${(serialMs / parMs).toFixed(1)}× faster through the fabric's parallel software backend — the seam the hardware co-processor slots into.`);
    expect(parMs).toBeLessThan(serialMs);

    // ── 7. Isolation + combinations ────────────────────────────────────────
    const views = isolateDimensions({ d: Object.fromEntries(ALL_AXES.map((_, i) => [i, { n: i }])) } as any,
      ALL_AXES.map((axisName, axisIndex) => ({ axisIndex, axisName })), (f: any, i) => f.d[i]);
    expect(views).toHaveLength(32);
    const combo = await combinators.voiceWeakness(1, { pitchMeanHz: vf.pitchMeanHz }, { axisIndex: cw.axisIndex, score: cw.score });
    demo.push(`### Sister combinations (${SISTER_COMBINATIONS.length} registered)\nLive invocation of "${combo.combination}" over the real voice + weakness outputs returned engines [${combo.engines.join(", ")}] and logged to the ledger path.`);

    // ── Write the docs ─────────────────────────────────────────────────────
    const env = `Node ${process.version}, single commodity container CPU, ${new Date().toISOString().slice(0, 10)}`;
    writeFileSync(join(__dirname, "..", "docs", "PATENT_BENCHMARKS.md"), `# Patent Engine Benchmarks — Software Embodiments

Measured by \`scripts/patentBenchmarks.test.ts\` (rerun it to regenerate).
Environment: ${env}. These are SOFTWARE-embodiment numbers on commodity
hardware — they are not hardware co-processor figures, and no filing should
present them as such. Hardware embodiments inherit the same interfaces.

| Benchmark | Measured | Rate / note |
|---|---|---|
${bench.join("\n")}
`);
    writeFileSync(join(__dirname, "..", "docs", "PATENT_PROTOTYPE_DEMONSTRATION.md"), `# Working Prototype Demonstration — Transcript

Generated live by \`scripts/patentBenchmarks.test.ts\` against the engines as
shipped in this repository (${env}). Each section is a real invocation with
real output — the "working prototype demonstration" the filings reference,
for the software embodiments only.

${demo.join("\n\n")}

### Platform context
These engines run inside the live joinaqal.com application: the consensus
bus and voice pipeline execute on every scored assessment; the ledger
records scores, matches, floors, and calibration updates; /api/ledger/verify
exposes public chain verification.
`);
    console.log("docs written");
  }, 300000);
});

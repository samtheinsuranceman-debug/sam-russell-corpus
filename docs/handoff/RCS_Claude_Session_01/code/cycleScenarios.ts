export const SCENARIO_COUNT = SCENARIOS.length;

export function scenario(id: string): Scenario | undefined {
  return SCENARIOS.find((s) => s.id === id);
}

/** Scenarios in a tier, most-likely sequence first. */
export function byTier(tier: CombinationTier): Scenario[] {
  return SCENARIOS.filter((s) => s.tier === tier)
    .sort((a, b) => a.sequenceRank - b.sequenceRank || a.id.localeCompare(b.id));
}

/** Every scenario that uses this mechanism anywhere in its sequence. */
export function usingMechanism(id: MechanismId): Scenario[] {
  return SCENARIOS.filter((s) => s.sequence.includes(id));
}

/** The factors that carry the most weight across the whole library. */
export function heaviestInfluences(limit = 10): Array<{ factor: string; appearances: number; meanScore: number }> {
  const tally = new Map<string, number[]>();
  for (const s of SCENARIOS) {
    for (const i of s.influences) {
      const prev = tally.get(i.factor) ?? [];
      prev.push(i.score);
      tally.set(i.factor, prev);
    }
  }
  return Array.from(tally.entries())
    .map(([factor, scores]) => ({
      factor,
      appearances: scores.length,
      meanScore: Math.round((scores.reduce((a, b) => a + b, 0) / scores.length) * 10) / 10,
    }))
    .sort((a, b) => b.appearances * b.meanScore - a.appearances * a.meanScore)
    .slice(0, limit);
}

/**
 * THE SCENARIO LIBRARY — which combinations of mechanisms are worth running,
 * in what order, for whom, and what emerges that neither one produces alone.
 *
 * ## Why combinations rather than mechanisms
 *
 * Every mechanism in `cycleEngine.ts` has a bottleneck, and the bottleneck is
 * the whole story. Velocity banking is bounded by surplus. BRRRR is bounded by
 * the capital you have for the next down payment. A policy loan is bounded by
 * cash value that takes a decade to build. An equity share is bounded to one
 * agreement per property.
 *
 * Combinations matter because one mechanism's OUTPUT is frequently another
 * mechanism's BOTTLENECK. Velocity banking produces surplus, which is exactly
 * what BRRRR lacks. BRRRR produces capital, which is exactly what funds a
 * policy. A policy produces borrowable cash value that does not require
 * underwriting, which is exactly what an operator refused by a bank needs.
 *
 * That is the entire logic of this file: a combination is worth running when
 * one member relieves another's constraint. A combination where that is not
 * true is just two strategies being run at once, and it is listed here as
 * such where it appears.
 *
 * ## Sequence is not decoration
 *
 * The same set of mechanisms in a different order is a different strategy with
 * a different failure mode. Fund a policy before establishing surplus and the
 * premium becomes the thing that breaks. Take an equity share before the
 * BRRRR engine is running and you have encumbered the property that would have
 * been refinanced. Every scenario therefore carries its sequence AND a
 * `sequenceRank` — 1 is the order that usually works, and the lower-ranked
 * orders are included because people run them and should see what they cost.
 *
 * ## Influence scores
 *
 * Each scenario scores the factors that decide whether it applies, 1 to 10.
 * A 10 means the scenario collapses without it. A 3 means it helps. These are
 * judgements about mechanism design, not measurements, and they are here so a
 * reader can argue with them rather than absorb them.
 */

import type { MechanismId } from './cycleEngine';

export type CombinationTier = 'pair' | 'triple' | 'quad' | 'full';

export const TIER_LABEL: Record<CombinationTier, string> = {
  pair: 'Two mechanisms',
  triple: 'Three mechanisms',
  quad: 'Four mechanisms',
  full: 'All five',
};

export const TIER_ORDER: readonly CombinationTier[] = ['pair', 'triple', 'quad', 'full'];

export interface Influence {
  readonly factor: string;
  /** 1–10. A 10 means the scenario collapses without it. */
  readonly score: number;
  readonly why: string;
}

export interface Scenario {
  readonly id: string;
  readonly tier: CombinationTier;
  readonly title: string;
  /** The mechanisms in the order they are run. */
  readonly sequence: readonly MechanismId[];
  /** 1 is the order that usually works. Higher numbers are orders people actually run. */
  readonly sequenceRank: number;
  /** Who this is, concretely. */
  readonly who: string;
  /** What was actually blocking them before. */
  readonly bottleneck: string;
  /** The constraint this combination removes. */
  readonly relieves: string;
  /** Why this order and not another. */
  readonly whyThisOrder: string;
  /** How the mechanisms feed each other. */
  readonly interaction: string;
  /** The property the combination has that neither member has alone. */
  readonly emergent: string;
  readonly influences: readonly Influence[];
  /** The failure mode. Always populated. */
  readonly watchFor: string;
}


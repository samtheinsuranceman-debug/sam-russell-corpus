// ============================================================
// OWNER VAULT CRYPTO — secrets at rest are AES-256-GCM under a key that
// lives only in the environment (OWNER_VAULT_KEY, 32 bytes hex).
//
// WHY. The owner panel stores up to 40 provider keys and 40 MCP URLs. A
// database dump must not be a key dump. With no OWNER_VAULT_KEY the vault
// refuses to store anything (fail closed), and reads of rows written under
// a different key fail loudly rather than returning garbage.
// ============================================================
import { createCipheriv, createDecipheriv, randomBytes, scryptSync, timingSafeEqual } from "node:crypto";

const ALG = "aes-256-gcm";

export function vaultKeyConfigured(env: NodeJS.ProcessEnv = process.env): boolean {
  return /^[0-9a-fA-F]{64}$/.test(env.OWNER_VAULT_KEY ?? "");
}

function key(env: NodeJS.ProcessEnv = process.env): Buffer {
  if (!vaultKeyConfigured(env)) throw new Error("OWNER_VAULT_KEY is not configured (32 bytes hex); the owner vault is disabled");
  return Buffer.from(env.OWNER_VAULT_KEY!, "hex");
}

/** iv.tag.ciphertext, base64 each, joined by '.' */
export function sealSecret(plain: string, env: NodeJS.ProcessEnv = process.env): string {
  const iv = randomBytes(12);
  const cipher = createCipheriv(ALG, key(env), iv);
  const ct = Buffer.concat([cipher.update(plain, "utf8"), cipher.final()]);
  return [iv.toString("base64"), cipher.getAuthTag().toString("base64"), ct.toString("base64")].join(".");
}

export function openSecret(sealed: string, env: NodeJS.ProcessEnv = process.env): string {
  const [iv, tag, ct] = sealed.split(".");
  if (!iv || !tag || !ct) throw new Error("sealed secret is malformed");
  const decipher = createDecipheriv(ALG, key(env), Buffer.from(iv, "base64"));
  decipher.setAuthTag(Buffer.from(tag, "base64"));
  return Buffer.concat([decipher.update(Buffer.from(ct, "base64")), decipher.final()]).toString("utf8");
}

/** What the panel shows: never the secret, only enough to recognise it. */
export function maskSecret(plain: string): string {
  if (plain.length <= 8) return "•".repeat(plain.length);
  return `${plain.slice(0, 3)}…${plain.slice(-4)} (${plain.length} chars)`;
}

// ── Passphrase (33+ characters or 16+ words) ─────────────────────────────────
// Stored as scrypt$salt$hash in OWNER_PANEL_PASSPHRASE_HASH; generated by scripts/owner_panel_passphrase_hash.mjs.

// N=2^15, r=8 needs 32 MiB; Node's default maxmem is exactly 32 MiB, so it is raised explicitly.
const SCRYPT = { N: 1 << 15, r: 8, p: 1, maxmem: 64 * 1024 * 1024 } as const;

export const PASSPHRASE_MIN_CHARS = 33;
export const PASSPHRASE_MIN_WORDS = 16;

export function passphraseMeetsPolicy(p: string): boolean {
  const words = p.trim().split(/\s+/).filter(Boolean);
  return p.length >= PASSPHRASE_MIN_CHARS || words.length >= PASSPHRASE_MIN_WORDS;
}

export function hashPassphrase(p: string, salt: Buffer = randomBytes(16)): string {
  const h = scryptSync(p.normalize("NFKC"), salt, 64, SCRYPT);
  return `scrypt$${salt.toString("base64")}$${h.toString("base64")}`;
}

export function verifyPassphrase(p: string, stored: string | undefined): boolean {
  if (!stored) return false;
  const [scheme, salt, hash] = stored.split("$");
  if (scheme !== "scrypt" || !salt || !hash) return false;
  const expected = Buffer.from(hash, "base64");
  const got = scryptSync(p.normalize("NFKC"), Buffer.from(salt, "base64"), expected.length, SCRYPT);
  return got.length === expected.length && timingSafeEqual(got, expected);
}
